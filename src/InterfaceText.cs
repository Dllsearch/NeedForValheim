    static string ReplaceFragment(string text,string key,string value) {
        var pattern=(char.IsLetterOrDigit(key[0])?@"(?<!\w)":"")+Regex.Escape(key)+(char.IsLetterOrDigit(key[key.Length-1])?@"(?!\w)":"");
        return Regex.Replace(text,pattern,value);
    }
    public static string Translate(string text,bool german) {
        if(!german||string.IsNullOrEmpty(text))return text;
        foreach(var pair in German)if(text==pair.Key)return pair.Value;
        foreach(var pair in Fragments)text=ReplaceFragment(text,pair.Key,pair.Value);
        return text;
